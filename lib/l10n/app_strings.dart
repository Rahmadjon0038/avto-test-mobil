import 'package:flutter/widgets.dart';
import 'package:shared_preferences/shared_preferences.dart';

class AppLanguageStore {
  static const String _key = 'app_language_code_v1';
  static const String uzLatn = 'uz_latn';
  static const String uzCyrl = 'uz_cyrl';
  static const String ru = 'ru';
  static String _currentCode = uzLatn;

  static const List<String> supportedCodes = <String>[
    uzLatn,
    uzCyrl,
    ru,
  ];

  static Future<String?> load() async {
    final prefs = await SharedPreferences.getInstance();
    final code = prefs.getString(_key);
    if (code == null || !supportedCodes.contains(code)) {
      return null;
    }
    _currentCode = code;
    return code;
  }

  static Future<void> save(String code) async {
    final prefs = await SharedPreferences.getInstance();
    final next = supportedCodes.contains(code) ? code : uzLatn;
    _currentCode = next;
    await prefs.setString(_key, next);
  }

  static String get currentCode => supportedCodes.contains(_currentCode) ? _currentCode : uzLatn;

  static void setCurrentCode(String code) {
    _currentCode = supportedCodes.contains(code) ? code : uzLatn;
  }
}

class AppLanguageScope extends InheritedWidget {
  const AppLanguageScope({
    super.key,
    required this.languageCode,
    required super.child,
  });

  final String languageCode;
  AppStrings get strings => AppStrings(languageCode);

  static AppLanguageScope of(BuildContext context) {
    final scope =
        context.dependOnInheritedWidgetOfExactType<AppLanguageScope>();
    assert(scope != null, 'AppLanguageScope not found in context');
    return scope!;
  }

  @override
  bool updateShouldNotify(AppLanguageScope oldWidget) {
    return languageCode != oldWidget.languageCode;
  }
}

